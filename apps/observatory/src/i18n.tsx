export const dictionaries: Record<Lang, Dictionary> = { en, ja };

export function useI18n() {
  const lang = useLang();
  const t = dictionaries[lang];
  return { lang, t };
}

export function formatTemporal(value: unknown, lang: Lang): string {
  const t = dictionaries[lang];
  if (value === null || typeof value !== "object" || Array.isArray(value))
    return t.unrecorded;
  const data = value as Record<string, unknown>;
  if (!data.precision) return t.unrecorded;
  if (data.precision === "unknown") return t.unknownTime;
  if (data.precision === "range")
    return lang === "ja"
      ? `${formatTemporal(data.start, lang)}〜${formatTemporal(data.end, lang)}`
      : `${formatTemporal(data.start, lang)} – ${formatTemporal(data.end, lang)}`;
  if (typeof data.value !== "string") return t.unrecorded;
  if (lang === "ja") {
    return data.value
      .split("-")
      .map((p, i) => `${Number(p)}${["年", "月", "日"][i]}`)
      .join("");
  }
  return data.value;
}
